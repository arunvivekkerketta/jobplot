/** Normalize a raw term: lowercase, trim, collapse whitespace, strip punctuation noise. */
export function normalizeTerm(raw: string): string {
  return raw
    .toLowerCase()
    .replace(/[.\-_]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

/** Resolve a raw term to its canonical form through the alias map. */
export function canonicalize(raw: string): string {
  const norm = normalizeTerm(raw);
  return ALIAS_MAP[norm] ?? norm;
}

